const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const word = (s) => new RegExp(`(^|[^a-z])${esc(s.toLowerCase())}([^a-z]|$)`);
// Longest names first, so "Navi Mumbai" wins over "Mumbai" and "Greater Kailash Jammu" over "Jammu".
const CITY_INDEX = REGIONS.flatMap((r) => r.cities.flatMap((c) => [c.name, ...(c.aliases ?? [])].map((n) => ({ n, re: word(n), region: r, city: c })))).sort(
  (a, b) => b.n.length - a.n.length,
);
const LOCALITY_INDEX = REGIONS.flatMap((r) => r.cities.flatMap((c) => c.localities.map((l) => ({ l, re: word(l), region: r, city: c })))).sort(
  (a, b) => b.l.length - a.l.length,
);
/**
 * Reads a place from an address or any text.
 * The PIN code settles the region; a known locality settles the city; otherwise the city name does.
 */
export function detectPlace(text) {
  if (!text) return null;
  const t = text.toLowerCase();
  const pin = t.match(/\b([1-8]\d{2})\s?(\d{3})\b/);
  const pinRegion = pin ? REGIONS.find((r) => r.pins.includes(pin[1])) : undefined;
  const loc = LOCALITY_INDEX.find((x) => (!pinRegion || x.region === pinRegion) && x.re.test(t));
  const city = loc ? { region: loc.region, city: loc.city } : CITY_INDEX.find((x) => (!pinRegion || x.region === pinRegion) && x.re.test(t));
  const region = city?.region ?? pinRegion;
  if (!region) return null;
  return {
    region: region.key,
    regionLabel: region.label,
    city: city?.city.name ?? "",
    state: city?.city.state ?? (region.key === "jammu-kashmir" ? "Jammu and Kashmir" : region.key === "mumbai" ? "Maharashtra" : "Delhi"),
    locality: loc?.l ?? "",
    pin: pin ? `${pin[1]}${pin[2]}` : "",
  };
}
