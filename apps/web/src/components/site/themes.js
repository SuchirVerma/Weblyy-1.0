export function fontsHref(t) {
  const fam = (f, w, italic) =>
    italic ? `family=${f.replace(/ /g, "+")}:ital,wght@0,${w.split(";").join(";0,")};1,${w.split(";").join(";1,")}` : `family=${f.replace(/ /g, "+")}:wght@${w}`;
  return `https://fonts.googleapis.com/css2?${fam(t.display, t.displayWeights, t.displayItalic)}&${fam(t.body, "400;500;600;700", false)}&display=swap`;
}
